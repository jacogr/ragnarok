"""Stage UI distribution files and generate immutable Nim asset arrays in build/.

Exposes build for deterministic asset staging/embedding. Make invokes main before native builds;
the pinned Nimony JS backend compiles src/ui/client.nim alongside src/ui/static/ assets.
"""
from pathlib import Path
import gzip
import io
import os
import subprocess
from setup_nimony import installed as native_tools, cache_directory
from setup_web import installed as web_tools
from setup_minifier import installed as minifier_tool

ROOT = Path(__file__).resolve().parents[1]


# Encode raw bytes, including NUL and non-UTF-8 assets, without source interpolation or Unicode conversion.
def literal(data):
    """Return a Nim string literal whose bytes exactly match the supplied immutable asset."""
    return '"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


# Keep unchanged inputs stable for compiler caches; changed bytes always update the manifest source.
def write_changed(path, data):
    """Write generated bytes only when absent or different, without following output symlinks."""
    if path.is_symlink():
        raise ValueError('Symlink in UI build output: ' + str(path))
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_bytes() != data:
        path.write_bytes(data)


# Fixed metadata keeps rebuilds byte-identical across time and source filenames.
def compressed(data):
    """Produce a gzip member without a timestamp or filename; runtime serving never compresses."""
    output = io.BytesIO()
    with gzip.GzipFile(filename='', mode='wb', fileobj=output, compresslevel=9, mtime=0) as stream:
        stream.write(data)
    return output.getvalue()


# Development keeps original bytes; explicit selection and CI enable the same native release transform.
def minify_enabled(environment):
    """Resolve UI_MINIFY=0|1, defaulting to enabled only for CI=1 or CI=true."""
    value = environment.get('UI_MINIFY', '1' if environment.get('CI') in ('1', 'true') else '0')
    if value not in ('0', '1'):
        # A misspelled release option must not silently ship readable development assets.
        raise ValueError('UI_MINIFY must be 0 or 1')
    return value == '1'


# Use transform mode so URLs, script globals and separate asset names retain their runtime contracts.
def minified(binary, name, data):
    """Minify JS/CSS before gzip; keep every other asset byte-exact and propagate parser failures."""
    suffix = Path(name).suffix
    if suffix not in ('.js', '.css'):
        # HTML and binary assets are outside this transform's scope.
        return data
    return subprocess.run([str(binary), '--loader='+suffix[1:], '--minify',
                           '--charset=utf8', '--sourcefile='+name], input=data,
                          stdout=subprocess.PIPE, check=True).stdout


# Capture source bytes once, before updating output, so each staged file matches its embedded constant.
def build(source, stage, manifest, generated=None, minifier=None):
    """Gzip one public asset tree and embed sorted sidecar paths; reject symlink sources."""
    source, stage, manifest = Path(source), Path(stage), Path(manifest)
    if not source.is_dir() or source.is_symlink():
        raise ValueError('Missing or symlinked UI source directory: ' + str(source))
    if stage.is_symlink():
        raise ValueError('Symlinked UI stage directory: ' + str(stage))
    assets = []
    for path in sorted(source.rglob('*')):
        # A source symlink must never silently include external files or omit a directory subtree.
        if path.is_symlink():
            raise ValueError('Symlink in UI assets: ' + str(path))
        if path.is_file():
            name = path.relative_to(source).as_posix()
            if '\\' in name or any(ord(c) < 32 or ord(c) == 127 for c in name):
                raise ValueError('Invalid UI asset path: ' + name)
            assets.append((name, path.read_bytes()))
        elif not path.is_dir():
            raise ValueError('Non-regular UI asset: ' + str(path))
    if generated:
        # Generated application code joins the same byte-exact manifest as static public assets.
        for name, content in generated.items():
            if name in {path for path, _ in assets}:
                raise ValueError('Generated UI asset collides with a static file: '+name)
            assets.append((name, content))
    assets.sort(key=lambda asset: asset[0]) # Sort URL paths rather than host path components.
    if 'index.html' not in {name for name, _ in assets}:
        raise ValueError('UI distribution requires index.html')
    if minifier is not None:
        # Finish every transform before replacing staged output; malformed release assets fail the build.
        assets = [(name, minified(minifier, name, data)) for name, data in assets]
    # Only gzip representations are staged/embedded; identity bytes are build-time inputs only.
    assets = sorted(((name+'.gz', compressed(content)) for name, content in assets),
                    key=lambda asset: asset[0]) # Suffixes can change ordering for prefix-related names.
    # Staging is build-owned output. Replace the tree only when its contents differ, removing stale assets.
    expected = {name for name, _ in assets}
    if stage.exists():
        for path in sorted(stage.rglob('*'), reverse=True):
            if path.is_symlink():
                raise ValueError('Symlink in UI build output: ' + str(path))
            if path.is_file() and path.relative_to(stage).as_posix() not in expected:
                path.unlink()
            elif path.is_dir() and not any(path.iterdir()):
                path.rmdir()
    for name, data in assets:
        write_changed(stage/name, data)
    header = ('# Copyright (c) 2026 Ragnarök contributors\n'
              '# SPDX-License-Identifier: MIT OR Apache-2.0\n\n'
              '## Generated immutable UI path/data arrays. Rebuild with make ui-assets.\n\n')
    paths = ',\n'.join('    ' + literal(name.encode('utf-8')) for name, _ in assets)
    data = ',\n'.join('    ' + literal(content) for _, content in assets)
    text = header + 'const\n  EmbeddedPaths = [\n' + paths + '\n  ]\n  EmbeddedData = [\n' + data + '\n  ]\n'
    write_changed(manifest, text.encode('utf-8'))
    return len(assets)


# The application is compiled by Nimony; bootstrap Nim is used only to build jorogumo itself.
def compile_client():
    """Compile the browser-only UI and retain diagnostics; backend identity separates compiler caches."""
    compiler, _ = native_tools()
    backend, identity = web_tools()
    folder = ROOT/'build/ui-client'
    folder.mkdir(parents=True, exist_ok=True)
    output = folder/'app.js'
    cache = cache_directory(compiler, folder, 'browser-'+identity[:16])
    command = [str(compiler), 'j', '--browser', '-d:release', '--mm:arc', '-d:ragnarokBrowser',
               '--nimcache:'+str(cache), '--out:'+str(output), str(ROOT/'src/ui/client.nim')]
    environment = {**os.environ, 'PATH': str(backend.parent)+os.pathsep+os.environ['PATH']}
    with (folder/'compile.log').open('w') as log:
        subprocess.run(command, cwd=ROOT, env=environment, stdout=log, stderr=subprocess.STDOUT, check=True)
    return output.read_bytes()


# Make owns tool preparation; this step emits the complete distribution and embedded manifest.
def main():
    """Build the repository-owned static distribution and its compile-time manifest."""
    minifier = minifier_tool() if minify_enabled(os.environ) else None
    count = build(ROOT/'src/ui/static', ROOT/'build/ui', ROOT/'build/ui_assets.nim',
                  {'app.js': compile_client()}, minifier=minifier)
    print(f'Embedded UI manifest: {count} assets; minified={minifier is not None}; staged in build/ui/')


if __name__ == '__main__':
    main()
