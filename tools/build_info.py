"""Generate immutable application/compiler metadata before every native Make build.

src/version.json supplies the application version; RAGNAROK_VERSION can override it.
The UTC timestamp is captured once during generation (or supplied by SOURCE_DATE_EPOCH).
RAGNAROK_REVISION can
supply an archive's source revision; Git builds capture the full HEAD and a dirty marker.
Compiler identity comes from the nightly pin validated by Make's toolchain prerequisite.
Gray Paper identity comes from the recorded specification pin, including its release status.
"""
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


# Keep embedded identity bounded and single-line, independent of CLI/JSON escaping at use sites.
def checked(value):
    """Reject empty, overlong or non-printable metadata instead of silently changing identity."""
    if not isinstance(value, str) or not value or len(value) > 128 or any(ord(c) < 32 or ord(c) > 126 for c in value):
        raise ValueError('Build identity must contain 1–128 printable ASCII characters')
    return value


# Source archives explicitly report unknown unless their packager supplies the original revision.
def revision(root):
    """Capture a full Git identity, including tracked/untracked edits but excluding ignored builds."""
    try:
        repository = subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], cwd=root,
                                             stderr=subprocess.DEVNULL, text=True).strip()
        if Path(repository).resolve() != Path(root).resolve():
            # An archive unpacked inside another checkout must not inherit that parent's identity.
            return 'unknown'
        head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root,
                                       stderr=subprocess.DEVNULL, text=True).strip()
        dirty = subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=normal'],
                                        cwd=root, text=True)
    except (FileNotFoundError, subprocess.CalledProcessError):
        # Archives without repository metadata remain buildable without claiming a source commit.
        return 'unknown'
    return head + ('-dirty' if dirty else '')


# Capture build time in UTC; reproducible packagers can supply the standard Unix epoch input.
def timestamp(environment):
    """Return a fixed ISO 8601 build instant, rejecting malformed/out-of-range epoch overrides."""
    if 'SOURCE_DATE_EPOCH' in environment:
        # Restrict overrides to Unix seconds within the representable UTC calendar.
        epoch = environment['SOURCE_DATE_EPOCH']
        if not epoch.isascii() or not epoch.isdecimal() or int(epoch) > 253402300799:
            raise ValueError('SOURCE_DATE_EPOCH must be Unix seconds in range 0..253402300799')
        instant = datetime.fromtimestamp(int(epoch), timezone.utc)
    else:
        # Ordinary builds capture the generator's time, never startup or RPC request time.
        instant = datetime.now(timezone.utc)
    return instant.isoformat(timespec='seconds').replace('+00:00', 'Z')


# Changed inputs invalidate compiler caches; unchanged builds retain the manifest's bytes and mtime.
def build(root, environment):
    """Write the shared Nim constants and return their values for build-tool verification."""
    root = Path(root)
    pins = json.loads((root/'spec/toolchain.json').read_text())
    application = json.loads((root/'src/version.json').read_text())
    graypaper = json.loads((root/'spec/pins.json').read_text())['graypaper']
    values = dict(AppVersion=environment.get('RAGNAROK_VERSION', application['version']),
                  AppRevision=(environment['RAGNAROK_REVISION'] if 'RAGNAROK_REVISION' in environment
                               else revision(root)),
                  CompilerVersion=pins['version'], CompilerRevision=pins['commit'],
                  GrayPaperVersion=graypaper['version'], GrayPaperRevision=graypaper['commit'],
                  GrayPaperReleaseStatus=graypaper['release_status'],
                  GrayPaperBaseRelease=graypaper['base_release'],
                  BuildTimestamp=timestamp(environment))
    source = '# Generated by tools/build_info.py; do not edit.\n'
    for name, value in values.items():
        # Hex bytes are Nim literals even when packagers include quotes or backslashes in a label.
        literal = ''.join(f'\\x{byte:02x}' for byte in checked(value).encode('ascii'))
        source += f'const {name}* = "{literal}"\n'
    output = root/'build/build_info.nim'
    if output.is_symlink():
        # A generated manifest must never overwrite a file outside the owned build tree.
        raise ValueError('Symlink in build metadata output')
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.is_file() or output.read_text() != source:
        # Avoid unnecessary semantic compilation when identity has not changed.
        output.write_text(source)
    return values


# Importing the generator has no filesystem, Git or compiler side effects.
if __name__ == '__main__':
    build(ROOT, os.environ)
