"""Build the missing JS backend from the exact dependency recorded by the pinned Nimony compiler.

Exposes ensure and installed for Make/UI builds. Sources are checksum-verified, unmodified sibling
archives under build/. The pinned formatter distribution supplies the compiler bootstrap only;
all application JavaScript is generated by the existing pinned Nimony compiler.

TODO: When the pinned nightly includes bin/jorogumo on all supported platforms, remove this
bootstrap and spec/web-toolchain.json; use the nightly backend directly. See spec/ui-browser.md
for the removal checklist. Do not keep this as a parallel self-build fallback.
"""
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess
import tarfile
from toolchain_archives import ROOT, download, extract
from setup_nimony import installed as native_tools, host_pins

DESTINATION = ROOT/'build/web-toolchain'
PINS = ROOT/'spec/web-toolchain.json'


# Stable tree identities catch edits to cached upstream sources before a backend build or reuse.
def tree_hash(root):
    """Hash source paths and file/link bytes; ignore directories, which contain no compiler input."""
    digest = hashlib.sha256()
    for path in sorted(root.rglob('*'), key=lambda item: item.relative_to(root).as_posix()):
        if path.is_symlink():
            content = b'link:' + os.readlink(path).encode()
        elif path.is_file():
            content = path.read_bytes()
        else:
            continue
        digest.update(path.relative_to(root).as_posix().encode() + b'\0')
        digest.update(hashlib.sha256(content).digest())
    return digest.hexdigest()


# Archives remain the authority even if an interrupted build left an extracted source tree behind.
def source(entry, destination):
    """Return verified pristine sources, preserving the sibling names required by upstream nim.cfg."""
    archive = DESTINATION/(destination.name+'-'+entry['commit']+'.tar.gz')
    raw = download(entry, archive)
    # Compare against every archive file/link before trusting a cached extraction.
    expected = hashlib.sha256()
    with tarfile.open(fileobj=io.BytesIO(raw)) as tar:
        entries = sorted((member for member in tar.getmembers() if member.isfile() or member.issym()),
                         key=lambda member: '/'.join(Path(member.name).parts[1:]))
        for member in entries:
            name = '/'.join(Path(member.name).parts[1:])
            content = b'link:' + member.linkname.encode() if member.issym() else tar.extractfile(member).read()
            expected.update(name.encode() + b'\0')
            expected.update(hashlib.sha256(content).digest())
    if not destination.exists():
        extracted = extract(raw, destination.parent/(destination.name+'-extract'))
        extracted.rename(destination)
    if tree_hash(destination) != expected.hexdigest():
        raise ValueError('Cached web backend sources changed; restore with make clean')
    return destination


# Bootstrap Nim comes from the already pinned formatter archive, without adding it to application PATH.
def bootstrap_compiler(formatter):
    """Check the bootstrap executable against the trusted release archive before executing it."""
    pins = host_pins(json.loads((ROOT/'spec/toolchain.json').read_text()))
    entry = pins['formatter_download']
    archive = ROOT/'build/toolchain'/('formatter-'+entry['sha256']+'.archive')
    raw = download(entry, archive)
    compiler = formatter.resolve().with_name('nim')
    with tarfile.open(fileobj=io.BytesIO(raw)) as tar:
        members = [member for member in tar.getmembers() if member.name.endswith('/bin/nim')]
        if len(members) != 1:
            raise ValueError('Formatter archive lacks one bootstrap compiler')
        expected = hashlib.sha256(tar.extractfile(members[0]).read()).hexdigest()
    if hashlib.sha256(compiler.read_bytes()).hexdigest() != expected:
        raise ValueError('Bootstrap compiler differs from its pinned archive')
    return compiler, expected


# Read-only callers require a prepared backend whose executable and source pins still match.
def installed():
    """Return the prepared backend and its cache identity; Make owns preparation sequencing."""
    manifest = json.loads((DESTINATION/'environment.json').read_text())
    if manifest['pins_sha256'] != hashlib.sha256(PINS.read_bytes()).hexdigest():
        raise ValueError('Web backend pins changed; run make web-toolchain')
    backend = Path(manifest['backend'])
    if hashlib.sha256(backend.read_bytes()).hexdigest() != manifest['backend_sha256']:
        raise ValueError('Web backend executable changed; run make web-toolchain')
    return backend, manifest['backend_sha256']


def ensure():
    """Restore the compiler's missing backend without changing compiler pins or dependency sources."""
    _, formatter = native_tools()
    pins = json.loads(PINS.read_text())
    native = json.loads((ROOT/'spec/toolchain.json').read_text())
    if pins['nimony']['commit'] != native['commit']:
        raise ValueError('Web backend sources must match the pinned compiler')
    DESTINATION.mkdir(parents=True, exist_ok=True)
    # Keep upstream sibling-relative configuration intact, in a revision-specific build-owned directory.
    parent = DESTINATION/'sources'/(pins['nimony']['commit'][:12]+'-'+pins['nativenif']['commit'][:12])
    nimony = source(pins['nimony'], parent/'nimony')
    nativenif = source(pins['nativenif'], parent/'nativenif')
    declared = (nimony/'src/nativenif.commit').read_text().split()[0]
    if declared != pins['nativenif']['commit']:
        raise ValueError('Backend revision does not match the compiler source pin')
    hashes = {name: tree_hash(path) for name, path in [('nimony', nimony), ('nativenif', nativenif)]}
    bootstrap, bootstrap_hash = bootstrap_compiler(formatter)
    stamp = DESTINATION/'environment.json'
    old = json.loads(stamp.read_text()) if stamp.exists() else {}
    fingerprint = dict(pins_sha256=hashlib.sha256(PINS.read_bytes()).hexdigest(),
                       source_hashes=hashes, bootstrap_sha256=bootstrap_hash)
    if all(old.get(key) == value for key, value in fingerprint.items()):
        try:
            backend, _ = installed()
            print('Pinned web backend ready: '+str(backend))
            return backend
        except (OSError, ValueError):
            pass # A missing/damaged generated executable is rebuilt from the verified sources.
    backend = DESTINATION/'bin/jorogumo'
    backend.parent.mkdir(parents=True, exist_ok=True)
    command = [str(bootstrap), 'c', '-d:release', '--warningAsError:ProveInit:off',
               '--warningAsError:Uninit:off', '--nimcache:'+str(DESTINATION/'bootstrap-cache'),
               '--out:'+str(backend), str(nativenif/'src/jorogumo/jorogumo.nim')]
    with (DESTINATION/'bootstrap.log').open('w') as log:
        subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, check=True)
    manifest = {**fingerprint, 'backend': str(backend),
                'backend_sha256': hashlib.sha256(backend.read_bytes()).hexdigest()}
    stamp.write_text(json.dumps(manifest, indent=2)+'\n')
    print('Built pinned web backend: '+str(backend))
    return backend


if __name__ == '__main__':
    ensure()
