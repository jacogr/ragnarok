proc fuzzPresetPolicy*(preset: ChainPreset): CurrentDownloadPolicyResult =
  ## Materialize and validate one immutable profile policy without runtime files, cwd assumptions or compiler-only test helpers.
  let parameters = presetParameters(preset).value
  let cores = parameters.get(coreCount)
  let validators = cores*3
  var text = PolicyTemplate
  for (token, value) in [("cores", cores), ("validators", validators), ("epoch", parameters.get(
      epochPeriod)), ("tickets", parameters.get(maxTicketsPerBlock)), ("tail", parameters.get(
          epochTailStart)),
      ("rotation", parameters.get(rotationPeriod)), ("lookup", parameters.get(maxLookupAnchorAge)),
      ("blockGas", parameters.get(blockGasLimit)), ("reportGas", parameters.get(maxAccumulateGas)),
      ("queueHashes", cores*80), ("historyPackages", cores*8), ("projectionRows", validators*2),
      ("comparisons", validators*validators), ("ancestors", parameters.get(maxLookupAnchorAge)+1)]:
    # Catalog fields are bounded fixed-width scalars and the three reviewed presets keep every product below uint64.
    text = text.replace("@" & token & "@", $value)
  decodeCurrentDownloadPolicy(text)
