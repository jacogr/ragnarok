"""Emit explicit JamV1 handlers/lowering from reviewed source-shaped operation families.

The generator keeps each scalar opcode a distinct function pointer and each memory
opcode specialized on memory kind. No opcode switch executes in the dispatch loop.
Expected results always come from the independent Rust oracle, never this generator.
"""
from formatting import nim
import argparse
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
HEADER = '''# Copyright (c) 2026 Ragnarök contributors
# SPDX-License-Identifier: MIT OR Apache-2.0

## Generated by generate_handlers.py from the reviewed interpreter.rs handler families.
## Included into engine.nim so the source handler functions share private instance state.

'''


def generate():
    """Translate opcode families while refusing any opcode not explicitly accounted for."""
    names = re.findall(r'    op_(\w+) = ', (HERE / 'opcodes.nim').read_text())
    scalar, branches, lowering = [], [], []
    for name in names:
        op = f'Opcode.op_{name}'
        if name in ('trap', 'invalid'):
            lower = 'instance.emit(trapHandler, [parsed.offset, 0\'u32, 0, 0])'
        elif name == 'unlikely':
            lower = 'discard'
        elif name == 'fallthrough':
            lower = 'instance.emit(unresolvedJump[true], [parsed.offset, parsed.nextOffset, 0\'u32, 0])'
        elif name == 'jump':
            lower = 'instance.emit(unresolvedJump[false], [parsed.offset, instruction.x, 0\'u32, 0])'
        elif name == 'ecalli':
            lower = 'instance.emit(ecalliHandler, [parsed.offset, instruction.x, 0\'u32, 0])'
        elif name == 'jump_indirect':
            lower = 'instance.emit(indirectHandler, [parsed.offset, uint32(register(instruction.a)), instruction.x, 0\'u32])'
        elif name == 'load_imm_and_jump':
            lower = 'instance.emit(unresolvedLoadJump, [parsed.offset, uint32(register(instruction.a)), instruction.x, instruction.y])'
        elif name == 'load_imm_and_jump_indirect':
            lower = 'instance.emit(loadIndirectHandler, [parsed.offset, uint32(register(instruction.a)) or (uint32(register(instruction.b)) shl 4), instruction.x, instruction.y])'
        elif name.startswith('branch_'):
            immediate = name.endswith('_imm')
            condition = name.removeprefix('branch_').removesuffix('_imm')
            relation = ('!=' if condition == 'not_eq' else '==' if condition == 'eq' else
                        '<=' if condition.startswith('less_or_equal') else '>=' if condition.startswith('greater_or_equal') else
                        '<' if condition.startswith('less') else '>')
            signed = condition.endswith('_signed')
            lhs = 'instance.regs[int(args[0])]'
            rhs = 'signed32(args[1])' if immediate else 'instance.regs[int(args[1])]'
            if signed:
                lhs, rhs = f'cast[int64]({lhs})', f'cast[int64]({rhs})'
            # All four source variants exist independently, with cached target status in the function pointer.
            for state in range(4):
                branches.append(f'proc h_{name}_{state}(instance: var Instance, offset: uint32): uint32\n  ## Forward declaration for source lazy branch patching.\n')
            for state in range(4):
                lines = [f'proc h_{name}_{state}(instance: var Instance, offset: uint32): uint32 =',
                         f'  ## Source {name}, resolved-arm mask {state}; only the taken unresolved arm is compiled.',
                         '  let args = instance.args[int(offset)]', f'  if {lhs} {relation} {rhs}:']
                for side, target_slot, other_slot, bit in [(True, 2, 3, 1), (False, 3, 2, 2)]:
                    if not side:
                        lines.append('  else:')
                    if state & bit:
                        lines.append(f'    return args[{target_slot}]')
                    else:
                        lines += [f'    let target = instance.resolveJump(args[{target_slot}])',
                                  '    assert target != high(uint32), "prevalidated branch failed resolution"',
                                  '    var updated = args', f'    updated[{target_slot}] = target']
                        if state == 0:
                            lines += [f'    let other = instance.offsets.get(args[{other_slot}])',
                                      '    if other.present and other.validJump:', f'      updated[{other_slot}] = other.target',
                                      f'      instance.patch(offset, h_{name}_3, updated)', '    else:',
                                      f'      instance.patch(offset, h_{name}_{bit}, updated)']
                        else:
                            lines.append(f'    instance.patch(offset, h_{name}_3, updated)')
                        lines.append('    return target')
                branches.append('\n'.join(lines)+'\n')
            true_pc = 'instruction.y' if immediate else 'instruction.x'
            rhs_arg = 'instruction.x' if immediate else 'uint32(register(instruction.b))'
            lower = f'''if validJump(instance.module.blob.code.view(), instance.module.blob.mask.view(), {true_pc}) and validJump(instance.module.blob.code.view(), instance.module.blob.mask.view(), parsed.nextOffset):
  instance.emit(h_{name}_0, [uint32(register(instruction.a)), {rhs_arg}, {true_pc}, parsed.nextOffset])
else:
  instance.emit(trapHandler, [parsed.offset, 0'u32, 0, 0])'''
        elif re.match(r'(load|store)_(imm_)?(indirect_)?[ui](8|16|32|64)$', name):
            is_load = name.startswith('load_')
            immediate = '_imm_' in name
            indirect = '_indirect_' in name
            ty = name.split('_')[-1]
            width = int(ty[1:]) // 8
            lines = [f'proc h_{name}[Dynamic: static[bool]](instance: var Instance, offset: uint32): uint32 =',
                     f'  ## Source {name}, specialized on the selected memory implementation.',
                     '  let args = instance.args[int(offset)]', '  instance.pc = args[0]']
            if immediate:
                address = 'uint32(instance.regs[int(args[1])]) + args[2]' if indirect else 'args[1]'
                value = 'signed32(args[3])' if indirect else 'signed32(args[2])'
                fields = ['parsed.offset'] + (['uint32(register(instruction.a))'] if indirect else []) + ['instruction.x', 'instruction.y']
            else:
                address = 'uint32(instance.regs[int(args[2])]) + args[3]' if indirect else 'args[2]'
                value = 'instance.regs[int(args[1])]'
                fields = ['parsed.offset', 'uint32(register(instruction.a))'] + (['uint32(register(instruction.b))'] if indirect else []) + ['instruction.x']
            lines.append(f'  let address = {address}')
            call = f'load[{width}](instance.{{memory}}, address)' if is_load else f'store[{width}](instance.{{memory}}, address, {value})'
            lines += ['  let access = when Dynamic:', f'      {call.format(memory="dynamic")}',
                      '    else:', f'      {call.format(memory="standard")}',
                      '  if access.kind != AccessKind.Ok: return instance.memoryFault(offset, access)']
            if is_load:
                val = f'cast[uint64](int64(cast[int{width*8}](uint{width*8}(access.value))))' if ty[0] == 'i' else 'access.value'
                lines.append(f'  instance.regs[int(args[1])] = {val}')
            lines.append('  offset + 1')
            scalar.append('\n'.join(lines)+'\n')
            fields += ["0'u32"] * (4-len(fields))
            lower = f'''if instance.module.dynamic:
  instance.emit(h_{name}[true], [{', '.join(fields)}])
else:
  instance.emit(h_{name}[false], [{', '.join(fields)}])'''
        else:
            lines = [f'proc h_{name}(instance: var Instance, offset: uint32): uint32 =',
                     f'  ## Direct translation of the source JamV1 {name} scalar handler.',
                     '  let args = instance.args[int(offset)]']
            fields = ['uint32(register(instruction.a))']
            if name == 'load_imm':
                expression = 'signed32(args[1])'
                fields += ['instruction.x']
            elif name == 'load_imm64':
                expression = 'uint64(args[1]) or (uint64(args[2]) shl 32)'
                fields += ['uint32(instruction.wide)', 'uint32(instruction.wide shr 32)']
            elif name in ('move_reg', 'sign_extend_8', 'sign_extend_16', 'zero_extend_16', 'reverse_byte') or name.startswith('count_'):
                fields += ['uint32(register(instruction.b))']
                lines.append('  let value = instance.regs[int(args[1])]')
                if name == 'move_reg': expression = 'value'
                elif name.startswith('sign_extend_'):
                    bits = name.split('_')[-1]
                    expression = f'cast[uint64](int64(cast[int{bits}](uint{bits}(value))))'
                elif name == 'zero_extend_16': expression = 'uint64(uint16(value))'
                elif name == 'reverse_byte': expression = 'swap64(value)'
                else:
                    bits = name.split('_')[-1]
                    method = ('countSetBits' if 'count_set' in name else 'leadingZeroBits' if 'leading' in name else 'trailingZeroBits')
                    expression = f'uint64({method}(uint{bits}(value)))'
            elif name.startswith('cmov_'):
                immediate = name.endswith('_imm')
                fields += ['uint32(register(instruction.b))', 'instruction.x' if immediate else 'uint32(register(instruction.c))']
                cond = 'instance.regs[int(args[1])]' if immediate else 'instance.regs[int(args[2])]'
                val = 'signed32(args[2])' if immediate else 'instance.regs[int(args[1])]'
                cmp = '!=' if 'not_zero' in name else '=='
                lines += [f'  if {cond} {cmp} 0:', f'    instance.regs[int(args[0])] = {val}']
                expression = None
            else:
                immediate = '_imm' in name
                fields += ['uint32(register(instruction.b))', 'instruction.x' if immediate else 'uint32(register(instruction.c))']
                lhs = 'instance.regs[int(args[1])]'
                rhs = 'signed32(args[2])' if immediate else 'instance.regs[int(args[2])]'
                if '_alt_' in name: lhs, rhs = rhs, lhs
                bits = 32 if name.endswith('_32') else 64
                lines += [f'  let lhs = uint{bits}({lhs})', f'  let rhs = uint{bits}({rhs})']
                if name.startswith('negate_and_add'): expression = 'rhs - lhs'
                elif name.startswith('add'): expression = 'lhs + rhs'
                elif name.startswith('sub'): expression = 'lhs - rhs'
                elif name.startswith('mul_upper_signed_signed'): expression = 'cast[uint64](mulh64(cast[int64](lhs), cast[int64](rhs)))'
                elif name.startswith('mul_upper_signed_unsigned'): expression = 'cast[uint64](mulhsu64(cast[int64](lhs), rhs))'
                elif name.startswith('mul_upper_unsigned_unsigned'): expression = 'mulhu64(lhs, rhs)'
                elif name.startswith('mul'): expression = 'lhs * rhs'
                elif name.startswith(('div_', 'rem_')):
                    signed = '_signed_' in name
                    stem = name[:3] + ('s' if signed else 'u') + ('64' if bits == 64 else '')
                    expression = f'{stem}(cast[int{bits}](lhs), cast[int{bits}](rhs))' if signed else f'{stem}(lhs, rhs)'
                    if signed: expression = f'cast[uint{bits}]({expression})'
                elif name.startswith('set_'):
                    sign = '_signed' in name
                    left, right = (('cast[int64](lhs)', 'cast[int64](rhs)') if sign else ('lhs', 'rhs'))
                    expression = f'uint64({left} {"<" if "less_than" in name else ">"} {right})'
                elif name.startswith('shift_'):
                    amount = f'int(rhs and {bits-1})'
                    if 'arithmetic' in name: expression = f'cast[uint{bits}](cast[int{bits}](lhs) shr {amount})'
                    else: expression = f'lhs {"shl" if "left" in name else "shr"} {amount}'
                elif name.startswith('rotate_'):
                    expression = f'rotate{"Left" if "left" in name else "Right"}Bits(lhs, int(rhs and {bits-1}))'
                elif name in ('and', 'and_imm'): expression = 'lhs and rhs'
                elif name in ('or', 'or_imm'): expression = 'lhs or rhs'
                elif name in ('xor', 'xor_imm'): expression = 'lhs xor rhs'
                elif name == 'and_inverted': expression = 'lhs and not rhs'
                elif name == 'or_inverted': expression = 'lhs or not rhs'
                elif name == 'xnor': expression = 'not (lhs xor rhs)'
                elif name.startswith(('maximum', 'minimum')):
                    method = 'max' if name.startswith('maximum') else 'min'
                    expression = f'{method}(lhs, rhs)' if name.endswith('_unsigned') else f'cast[uint64]({method}(cast[int64](lhs), cast[int64](rhs)))'
                else: raise ValueError(f'untranslated opcode: {name}')
                if bits == 32: expression = f'signed32({expression})'
            if expression is not None: lines.append(f'  instance.regs[int(args[0])] = {expression}')
            lines.append('  offset + 1')
            scalar.append('\n'.join(lines)+'\n')
            fields += ["0'u32"] * (4-len(fields))
            lower = f'instance.emit(h_{name}, [{", ".join(fields)}])'
        lowering += [f'  of {op}:'] + ['    '+line for line in lower.splitlines()]
    lower_head = '''proc lower(instance: var Instance, parsed: ParsedInstruction) =
  ## Compiler visitor normalizes raw registers once and packs the source sixteen-byte Args.
  let instruction = parsed.instruction
  case instruction.opcode
'''
    return {'engine_scalar.nim': HEADER+'\n'.join(scalar),
            'engine_branches.nim': HEADER+'\n'.join(branches),
            'engine_lowering.nim': HEADER+lower_head+'\n'.join(lowering)+'\n'}


def main():
    """Generate source or verify committed translation bytes without modifying them."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generate().items():
        content = nim(content)
        path = HERE / name
        if args.check:
            assert path.read_text() == content, f'stale generated handler source: {name}'
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
