"""Check independent arithmetic witnesses and exact checked-in corpus reproduction."""
from pathlib import Path
import unittest
from state_account_deposit_oracle import MAX, ROWS, observation, cases, encoded

class DepositOracleTests(unittest.TestCase):
    """Tiny direct witnesses keep the arbitrary-precision reference independently reviewable."""
    def test_literals(self):
        """Cancellation and two-pool overflow cases must match authored expectations."""
        self.assertEqual(observation((3,121,20,100,2,3,449,0)), (449,0,1))
        self.assertEqual(observation((2,0,MAX,0,MAX,0,MAX,MAX)), (MAX,0,1))
        self.assertEqual(observation((3,0,MAX,0,MAX,0,MAX,MAX)), (0,1,0))
    def test_fixture(self):
        """Generated bytes, row size and positive/overflow populations remain stable."""
        self.assertEqual(encoded(), (Path(__file__).parent/'fixtures/account-deposit-corpus.txt').read_bytes())
        self.assertTrue(all(len(line)==148 for line in encoded().splitlines()))
        refusals=sum(observation(row)[1] for row in cases())
        self.assertGreaterEqual(refusals,256)
        self.assertGreaterEqual(ROWS-refusals,256)
