## File-boundary failures and success-only reasons retain strict checked extraction contracts.

import std/[cmdline, assertions, syncio]
import std/posix/posix
import ../../src/state/[checkpoint_file, checkpoint, store]
import ../../src/codec/bounded

proc main() {.raises.} =
  ## Real files feed the same public loader used at startup; cleanup runs before exit on every path.
  let mode = paramStr(1)
  var path = "build/state-checkpoint-file-result.bin"
  defer: discard posix.unlink(path.toCString()) # Generated bytes remain in the ignored workspace.
  if mode == "save-default":
    let outcome = default(CheckpointFileResult[StateStoreSnapshot])
    discard outcome.value # Snapshot publication payloads require genuine durable success too.
  elif mode == "default":
    let outcome = default(CheckpointFileResult[StateStore])
    discard outcome.value # Defaults do not contain restored state.
  elif mode == "reason-default":
    let outcome = default(CheckpointFileResult[StateStore])
    discard outcome.checkpointError # Default outer failures have no inner checkpoint reason.
  elif mode == "missing":
    discard loadFullCheckpoint("build/missing-state-checkpoint", default(StateStoreLimits),
        ByteLimit(100)).value # Missing files cannot expose a store.
  else:
    let snapshot = newStateStore([], default(StateStoreLimits)).value.snapshot.value
    writeFile(path, encodeFullCheckpoint(snapshot, ByteLimit(100)).value)
    if mode == "save-refused":
      discard saveFullCheckpoint(path, snapshot, ByteLimit(
          0)).value # Encoding refusal cannot expose a published snapshot.
    elif mode == "positive":
      assert sameStateSnapshot(saveFullCheckpoint(path, snapshot, ByteLimit(100)).value, snapshot)
      assert loadFullCheckpoint(path, default(StateStoreLimits), ByteLimit(
          100)).value.snapshot.error == StateStoreError.None
      writeFile(path, "invalid")
      assert loadFullCheckpoint(path, default(StateStoreLimits), ByteLimit(100)).checkpointError ==
          CheckpointError.InvalidFormat
    elif mode == "oversized":
      discard loadFullCheckpoint(path, default(StateStoreLimits), ByteLimit(
          0)).value # Size refusal has no partial bytes or state.
    elif mode == "reason-success":
      discard loadFullCheckpoint(path, default(StateStoreLimits), ByteLimit(
          100)).checkpointError # Success carries no error-only diagnostic.
    else:
      writeFile(path, "invalid")
      discard loadFullCheckpoint(path, default(StateStoreLimits), ByteLimit(
          100)).value # Decoder refusal cannot leak partial state.
try:
  main() # An unrelated file exception cannot satisfy the strict assertion probes.
except:
  quit(2)
