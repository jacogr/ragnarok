## Raw read extraction requires actual bounded EOF, including a real binary/empty success control.

import std/[cmdline, assertions]
import std/posix/posix
import ../../src/lib/atomic/file as atomic_file
import ../../src/codec/bounded

proc main() =
  ## Routine-local cleanup uses the pinned compiler's supported defer lowering.
  let mode = paramStr(1)
  if mode == "default":
    let outcome = default(BoundedFileResult)
    discard outcome.value # Default construction cannot authorize file bytes.
  elif mode == "missing":
    discard readBoundedFile("build/missing-bounded-file", ByteLimit(
        10)).value # Missing files cannot expose a prefix.
  else:
    var path = "build/state-bounded-file-read-result.bin"
    defer: discard posix.unlink(path.toCString()) # Only ignored generated bytes are removed.
    assert replaceAtomicFile(path, [0'u8, 255], ByteLimit(2)) == AtomicFileError.None
    if mode == "positive":
      assert readBoundedFile(path, ByteLimit(2)).value == @[0'u8, 255]
      assert replaceAtomicFile(path, [], ByteLimit(0)) == AtomicFileError.None
      assert readBoundedFile(path, ByteLimit(0)).value.len ==
          0 # Raw EOF success is meaningful even for an empty file.
    else:
      discard readBoundedFile(path, ByteLimit(0)).value # A short ceiling has no successful byte prefix.
main()
