## Real bounded files exercise startup-only restoration, typed refusals and descriptor-owner cleanup.

import std/[assertions, syncio]
import std/posix/posix
import ../../../src/state/checkpoint/file as checkpoint_file
import ../../../src/state/[checkpoint, store]
import ../../../src/codec/state/[trie as state_trie, layout as state_layout]
import ../../../src/codec/bounded
import ../../support/arc_evidence

const FileName = "state-checkpoint-file.bin"
proc policy(): StateStoreLimits =
  ## A value crossing one read chunk verifies chunk iteration without large fixtures.
  StateStoreLimits(trie: StateTrieLimits(items: ElementLimit(1), perValue: ByteLimit(4100),
    totalValueBytes: ByteLimit(4100), nodes: TrieNodeLimit(1024)),
    writes: ElementLimit(1), writeValueBytes: ByteLimit(4100))
proc cycle() =
  ## Successful files and decoder failures retire both read buffers and map owners before observation.
  assert loadFullCheckpoint(FileName, policy(), ByteLimit(5000)).error == CheckpointFileError.None
  assert loadFullCheckpoint(FileName, policy(), ByteLimit(1)).error ==
      CheckpointFileError.LimitExceeded
proc main() {.raises.} =
  ## Exercise exact and crossed chunk boundaries with real file bytes and independent output owners.
  var path = FileName
  defer: discard posix.unlink(path.toCString()) # Runner-local generated bytes retire even after a failed assertion.
  let absent = default(CheckpointFileResult[StateStore])
  assert absent.error == CheckpointFileError.Uninitialized
  assert loadFullCheckpoint("", policy(), ByteLimit(5000)).error == CheckpointFileError.InvalidPath
  var invalidPath = "xyz"
  invalidPath[1] = char(0)
  assert loadFullCheckpoint(invalidPath, policy(), ByteLimit(5000)).error ==
      CheckpointFileError.InvalidPath
  assert loadFullCheckpoint("missing-checkpoint.bin", policy(), ByteLimit(5000)).error ==
      CheckpointFileError.IoFailure
  assert loadFullCheckpoint(".", policy(), ByteLimit(5000)).error == CheckpointFileError.IoFailure
  var value = newSeq[byte](4100)
  for index in 0..<value.len:
    value[index] = byte(index mod 251) # Chunk boundaries must not duplicate, omit or reorder any raw octet.
  let original = newStateStore([StateEntry(key: default(StateKey), value: value)], policy()).value.snapshot.value
  let bytes = encodeFullCheckpoint(original, ByteLimit(5000)).value
  writeFile(FileName, bytes)
  let loaded = loadFullCheckpoint(FileName, policy(), ByteLimit(uint64(bytes.len)))
  assert loaded.error == CheckpointFileError.None
  assert encodeFullCheckpoint(loaded.value.snapshot.value, ByteLimit(5000)).value == bytes
  assert loadFullCheckpoint(FileName, policy(), ByteLimit(uint64(bytes.len - 1))).error ==
      CheckpointFileError.LimitExceeded
  assert loadFullCheckpoint(FileName, policy(), ByteLimit(0)).error ==
      CheckpointFileError.LimitExceeded
  var limits = policy()
  limits.trie.perValue = ByteLimit(4099)
  let refused = loadFullCheckpoint(FileName, limits, ByteLimit(5000))
  assert refused.error == CheckpointFileError.InvalidCheckpoint
  assert refused.checkpointError == CheckpointError.LimitExceeded
  writeFile(FileName, "")
  let empty = loadFullCheckpoint(FileName, policy(), ByteLimit(0))
  assert empty.error == CheckpointFileError.InvalidCheckpoint
  assert empty.checkpointError == CheckpointError.InvalidFormat
  writeFile(FileName, "invalid")
  assert loadFullCheckpoint(FileName, policy(), ByteLimit(5000)).checkpointError ==
      CheckpointError.InvalidFormat
  assert loaded.value.snapshot.value.lookup(default(StateKey)).value.bytes ==
      value # A restored owner survives later file replacement.
  writeFile(FileName, bytes)
  cycle()
  let before = getOccupiedMem()
  for iteration in 0..<1000:
    cycle() # Repeated read/close paths cannot retain owned buffers or restored snapshots.
  let after = getOccupiedMem()
  assert before == after
  recordArcRelease("state_checkpoint_file", 1000, before, after)
  echo "PASS state checkpoint files: bounded EOF, typed I/O and owned full-state loading"
try:
  main() # Filesystem exceptions cannot satisfy the explicit native success transcript.
except:
  quit(2)
