## Shared raw EOF reads retain exact binary bytes and typed failures without interpreting state/control formats.

import std/[assertions, syncio]
import std/posix/posix
import ../../../src/lib/atomic/file as atomic_file
import ../../../src/codec/bounded
import ../../support/arc_evidence

proc makeFifo(path: cstring, mode: Mode): cint {.importc: "mkfifo", cdecl, header: "<sys/stat.h>".}
  ## A real FIFO with no writer proves path opening cannot block before regular-file validation.

const FileName = "state-bounded-file-read.bin"
proc cycle() =
  ## Read/close success and one-byte-short refusal retire every private buffer before observation.
  assert readBoundedFile(FileName, ByteLimit(5000)).error == AtomicFileError.None
  assert readBoundedFile(FileName, ByteLimit(4999)).error == AtomicFileError.LimitExceeded
proc main() =
  ## Fixed chunks and ceiling-plus-one detection must preserve binary order, empty files and exact limits.
  var path = FileName
  var fifo = "state-bounded-file-read.fifo"
  discard posix.unlink(fifo.toCString()) # Remove only a runner-owned leftover from an interrupted prior test.
  assert makeFifo(fifo.toCString(), Mode(0o600)) == 0
  defer: discard posix.unlink(fifo.toCString())
  assert readBoundedFile(fifo, ByteLimit(5000)).error == AtomicFileError.IoFailure
  defer: discard posix.unlink(path.toCString()) # All generated bytes are runner-local and retire after retained-owner checks.
  let absent = default(BoundedFileResult)
  assert absent.error == AtomicFileError.Uninitialized
  assert readBoundedFile("", ByteLimit(5000)).error == AtomicFileError.InvalidPath
  var invalid = "xyz"
  invalid[1] = char(0)
  assert readBoundedFile(invalid, ByteLimit(5000)).error == AtomicFileError.InvalidPath
  assert readBoundedFile("missing-raw-checkpoint", ByteLimit(5000)).error ==
      AtomicFileError.IoFailure
  assert readBoundedFile(".", ByteLimit(5000)).error == AtomicFileError.IoFailure
  assert replaceAtomicFile(FileName, [], ByteLimit(0)) == AtomicFileError.None
  let empty = readBoundedFile(FileName, ByteLimit(0))
  assert empty.error == AtomicFileError.None and empty.value.len == 0
  var bytes = newSeq[byte](5000)
  for index in 0..<bytes.len:
    bytes[index] = byte(index mod 251) # Crossing a read chunk preserves every raw byte, including NUL/high octets.
  assert replaceAtomicFile(FileName, bytes, ByteLimit(5000)) == AtomicFileError.None
  let loaded = readBoundedFile(FileName, ByteLimit(5000))
  assert loaded.error == AtomicFileError.None
  assert loaded.value == bytes
  assert readBoundedFile(FileName, ByteLimit(high(uint64))).value == bytes
  for limit in [0'u64, 1, 4095, 4096, 4999]:
    assert readBoundedFile(FileName, ByteLimit(limit)).error == AtomicFileError.LimitExceeded
  assert replaceAtomicFile(FileName, [], ByteLimit(0)) == AtomicFileError.None
  assert loaded.value == bytes # Owned results survive later replacement of the file they came from.
  var copied = loaded.value
  copied[0] = 99
  assert loaded.value == bytes
  assert replaceAtomicFile(FileName, bytes, ByteLimit(5000)) == AtomicFileError.None
  cycle()
  let before = getOccupiedMem()
  for iteration in 0..<1000:
    cycle() # Raw file ownership is observed on the joined calling thread only.
  let after = getOccupiedMem()
  assert before == after
  recordArcRelease("state_bounded_file_read", 1000, before, after)
  echo "PASS bounded file reads: exact EOF, byte ceilings, typed failures and independent owners"
main()
