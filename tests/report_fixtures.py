"""Independent test-only OpenSSL Ed25519 fixtures over the pinned normative report signing message."""
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path
from report_oracle import ROOT, corpus, encode


# Import one known deterministic test seed through standard PKCS#8, then sign exact message bytes in OpenSSL.
def openssl_sign(seed, message):
    with tempfile.TemporaryDirectory(prefix='ragnarok-public-report-fixture-') as directory:
        folder = Path(directory)
        key, data, signature = folder/'test-key.der', folder/'message.bin', folder/'signature.bin'
        key.write_bytes(bytes.fromhex('302e020100300506032b657004220420') + seed)
        data.write_bytes(message)
        subprocess.run(['openssl','pkeyutl','-sign','-rawin','-inkey',str(key),'-keyform','DER',
                        '-in',str(data),'-out',str(signature)],capture_output=True,check=True)
        public = subprocess.check_output(['openssl','pkey','-inform','DER','-in',str(key),'-pubout','-outform','DER'],stderr=subprocess.PIPE)
        # The output must be the exact RFC 8410 Ed25519 SPKI, not an arbitrary trailing-byte extraction.
        assert public[:12] == bytes.fromhex('302a300506032b6570032100') and len(public) == 44
        signed = signature.read_bytes()
        assert len(signed) == 64
        return public[12:], signed


# Verify the independently installed test provider against a pinned nonempty RFC 8032 known-answer case.
def validate_provider():
    fixture = ROOT/'vectors/official/crypto/rfc8032.json'
    pin = json.loads((ROOT/'spec/crypto-pins.json').read_text())['rfc8032']['fixture_sha256']
    assert hashlib.sha256(fixture.read_bytes()).hexdigest() == pin
    values = json.loads(fixture.read_text())
    # A nonempty case works with OpenSSL versions that reject signing an empty pkeyutl input file.
    value = next(value for value in values if value['message'])
    key, signature = openssl_sign(bytes.fromhex(value['seed']),bytes.fromhex(value['message']))
    assert key.hex() == value['public'] and signature.hex() == value['signature']
    return subprocess.check_output(['openssl','version'],text=True).strip()


# All public deterministic test credentials are generated by OpenSSL, independently of the peer providers.
def fixtures():
    provider = validate_provider()
    values = []
    for name, value in corpus():
        wire = encode(value)
        message = b'$jam_guarantee' + hashlib.blake2b(wire,digest_size=32).digest()
        credentials = [openssl_sign(hashlib.sha256(f'ragnarok-public-test-seed-{i}'.encode()).digest(),message) for i in range(2)]
        assert credentials[0][0] != credentials[1][0]
        wrong_domain = openssl_sign(hashlib.sha256(b'ragnarok-public-test-seed-0').digest(),b'jam_guarantee'+message[14:])
        values.append(dict(name=name,wire=wire,message=message,credentials=credentials,wrong_domain=wrong_domain))
    return provider, values


# Query a complete native signing-message/verification preflight without asking it to generate reference signatures.
def check(binary, value, folder, credentials=None, wire=None):
    source = value['wire'] if wire is None else wire
    path = folder/'credential-report.bin'
    path.write_bytes(source)
    credentials = value['credentials'] if credentials is None else credentials
    args = [str(binary),'check',str(path),*[data.hex() for pair in credentials for data in pair]]
    result = subprocess.run(args,cwd=ROOT,capture_output=True,text=True,timeout=20)
    assert result.returncode == 0, (args[:4],result.returncode,result.stderr[-2000:])
    lines = result.stdout.splitlines()
    assert len(lines) == 1, result.stdout[:300]
    parts = lines[0].split()
    expected_message = b'$jam_guarantee' + hashlib.blake2b(source,digest_size=32).digest()
    assert len(parts) == 4 and parts[0] == 'VERIFY' and parts[1] == source.hex() and parts[2] == expected_message.hex()
    assert parts[3] in ('0','1')
    return parts[3] == '1'


# Valid credentials and independent wrong-key/signature/domain/report bindings exercise full M1/M2 composition.
def verify_composition(binary, folder, values):
    count = 0
    for value in values:
        assert check(binary,value,folder)
        count += 1
        for index in range(2):
            credentials = list(value['credentials'])
            key, signature = credentials[index]
            changed = bytearray(signature); changed[0] ^= 1
            credentials[index] = (key,bytes(changed))
            assert not check(binary,value,folder,credentials)
            count += 1
        # Changing a fixed hash retains valid report structure but must break the signed-report binding.
        changed = bytearray(value['wire']); changed[0] ^= 1
        assert not check(binary,value,folder,wire=bytes(changed))
        count += 1
        # Every newly serialized 0.8.0 field is bound by the guarantee signature.
        for field in ('shards','anchor-slot','lookup-state'):
            changed = bytearray(value['wire'])
            # A different valid shard count preserves structure, isolating signed-message binding.
            if field == 'shards':
                shards = int.from_bytes(changed[68:70],'little')
                changed[68:70] = (9 if shards == 6 else 6).to_bytes(2,'little')
            elif field == 'anchor-slot':
                changed[136] ^= 1 # Mutate one byte of the new E4 anchor timeslot.
            else:
                changed[240] ^= 1 # Mutate one byte of the new lookup-anchor state root.
            assert not check(binary,value,folder,wire=bytes(changed))
            count += 1
        # Swapping distinct credentials' public keys cannot authorize either unchanged signature.
        assert not check(binary,value,folder,[value['wrong_domain'],value['credentials'][1]])
        count += 1
        a,b = value['credentials']
        assert not check(binary,value,folder,[(b[0],a[1]),(a[0],b[1])])
        count += 1
    return count
